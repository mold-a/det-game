const MINUS = "−"; // типографский минус

/** Число со знаком: +15, −5, 0. */
export function signed(n) {
  if (n > 0) return `+${n}`;
  if (n < 0) return `${MINUS}${Math.abs(n)}`;
  return "0";
}

/** «балл» в нужной форме: 1 балл, 2 балла, 5 баллов. */
export function pointsWord(n) {
  const a = Math.abs(n) % 100;
  const b = a % 10;
  if (a > 10 && a < 20) return "баллов";
  if (b === 1) return "балл";
  if (b >= 2 && b <= 4) return "балла";
  return "баллов";
}

/** «после N неверных попыток» — родительный падеж: 1 неверной попытки, 3 неверных попыток. */
function afterAttempts(n) {
  const a = Math.abs(n) % 100;
  return a % 10 === 1 && a !== 11 ? `${n} неверной попытки` : `${n} неверных попыток`;
}

