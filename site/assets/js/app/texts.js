/** Описание записи журнала. labelFor(path) → название вопроса (из пакета). */
export function describeLogEntry(entry, labelFor = (p) => p) {
  const r = String(entry.r);
  const [kind, ...rest] = r.split(":");
  const R = T.scorelog.reason;
  switch (kind) {
    case "wrong":
      return R.wrong(labelFor(rest[0])); // wrong:<qpath>:<hash8> (или старый wrong:<qpath>)
    case "hint": {
      const lvl = rest.pop();
      return R.hint(labelFor(rest.join(":")), lvl);
    }
    case "bonus":
      return R.bonus(labelFor(rest.join(":")));
    case "final":
      return R.final(labelFor(rest.join(":")));
    case "lab":
      return R.lab;
    default:
      return R.other(r);
  }
}
